/** Проект + разобранные материалы + расчёт цены. */
export const projects = raw.map((item) => {
  const facade = byId(FACADES, item.facadeId);
  const facadeColor = byId(facade.colors, item.facadeColorId);
  const worktop = byId(WORKTOPS, item.worktopId);
  const worktopColor = byId(worktop.colors, item.worktopColorId);
  const fitting = byId(FITTINGS, item.fittingId);
  const layout = byId(LAYOUTS, item.layout);

  const estimate = calculate({
    wall: item.wall,
    layout: item.layout,
    facade,
    worktop,
    fitting,
    extras: item.extras,
  });

  return {
    ...item,
    facade,
    facadeColor,
    worktop,
    worktopColor,
    fitting,
    layout,
    estimate,
    url: `/projects/${item.slug}/`,
    /** Конфигурация для конфигуратора: ссылка «хочу такую же». */
    query: new URLSearchParams({
      wall: String(item.wall),
      layout: item.layout,
      facade: item.facadeId,
      color: item.facadeColorId,
      top: item.worktopId,
      topColor: item.worktopColorId,
      fitting: item.fittingId,
      extras: item.extras.join(','),
    }).toString(),
  };
});

export const getProject = (slug) => projects.find((item) => item.slug === slug);
